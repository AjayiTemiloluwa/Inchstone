// Regenerates src/lib/ai/appApi.generated.ts: a static registry of the app's own API route
// handlers (so the assistant can call any of them in-process) plus a one-line catalog per
// endpoint (query params + body fields) read from each handler's source.
//
//   node scripts/gen-ai-api-registry.js
//
// Run it again after adding or changing an API route.
const fs = require('fs')
const path = require('path')

const API = path.join(__dirname, '..', 'src', 'app', 'api')
const OUT = path.join(__dirname, '..', 'src', 'lib', 'ai', 'appApi.generated.ts')

// Never exposed to the assistant: other AI routes, schedulers, push plumbing, destructive resets,
// OAuth redirects, browser-only streaming and multipart/binary uploads.
const SKIP = [
  /^ai\//, /^cron\//, /^push\//, /^reset\//, /^seed\//, /^calendar\/(auth|callback)\//, /^icon\//,
  /^email-status\//, /^messages\/wait\//, /^applications\/import\//, /^applications\/template\//,
  /^applications\/\[id\]\/files/, /^widget\//, /^tasks\/due\//, /^deed-timers\//, /^notifications\//,
]

const files = []
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p)
    else if (e.name === 'route.ts') files.push(p)
  }
}
walk(API)

const routes = []
for (const f of files.sort()) {
  const rel = path.relative(API, path.dirname(f)).split(path.sep).join('/') + '/'
  if (SKIP.some((re) => re.test(rel))) continue
  const src = fs.readFileSync(f, 'utf8')
  const methods = [...src.matchAll(/export async function (GET|POST|PUT|PATCH|DELETE)\b([\s\S]*?)(?=\nexport async function |\s*$)/g)]
  if (!methods.length) continue
  const urlPath = '/api/' + rel.replace(/\/$/, '').replace(/\[(\w+)\]/g, ':$1')
  const info = {}
  for (const m of methods) {
    const body = m[2]
    const query = [...new Set([...body.matchAll(/searchParams\.get\(['"](\w+)['"]\)/g)].map((x) => x[1]))]
    const fields = new Set()
    for (const d of body.matchAll(/const \{([^}]+)\} = (?:body|await (?:req|request)\.json\(\)[^\n]*)/g)) {
      d[1].split(',').map((s) => s.trim().split(':')[0].split('=')[0].replace('...', '').trim()).filter(Boolean).forEach((s) => fields.add(s))
    }
    for (const d of body.matchAll(/\bbody\.(\w+)/g)) fields.add(d[1])
    info[m[1]] = { query, fields: [...fields].filter((x) => x !== 'userId') }
  }
  routes.push({ rel, urlPath, info, importPath: '@/app/api/' + rel.replace(/\/$/, '') + '/route' })
}

const lines = []
lines.push('// GENERATED by scripts/gen-ai-api-registry.js. Do not edit by hand.')
lines.push('/* eslint-disable */')
routes.forEach((r, i) => lines.push(`import * as r${i} from '${r.importPath}'`))
lines.push('')
lines.push('export interface AppRoute { pattern: string; mod: Record<string, unknown>; methods: string[] }')
lines.push('export const APP_ROUTES: AppRoute[] = [')
routes.forEach((r, i) => lines.push(`  { pattern: '${r.urlPath}', mod: r${i} as Record<string, unknown>, methods: ${JSON.stringify(Object.keys(r.info))} },`))
lines.push(']')
lines.push('')
lines.push('/** One line per endpoint: METHOD path ?query {body fields}. */')
const catalog = []
for (const r of routes) {
  for (const [method, v] of Object.entries(r.info)) {
    catalog.push(`${method} ${r.urlPath}${v.query.length ? ' ?' + v.query.join('&') : ''}${v.fields.length ? ' {' + v.fields.join(',') + '}' : ''}`)
  }
}
lines.push('export const APP_API_CATALOG: string[] = ' + JSON.stringify(catalog, null, 2))
fs.writeFileSync(OUT, lines.join('\n') + '\n')
console.log(`routes: ${routes.length}, catalog lines: ${catalog.length}`)
